"""Regenerates logo_aerosense.h (RGB565) from public/assets/aerosense-logo.svg.
Usage: python3 firmware/tft-display/tools/make_logo.py  (needs Pillow with WebP support)"""
import base64, io, pathlib, re
from PIL import Image

root = pathlib.Path(__file__).resolve().parents[3]
svg = (root / "public/assets/aerosense-logo.svg").read_text()
image = Image.open(io.BytesIO(base64.b64decode(re.search(r'base64,([^"]+)"', svg).group(1)))).convert("RGB")
HEIGHT = 120  # fits the 128 px tall screen in landscape
width = round(image.width * HEIGHT / image.height)
image = image.resize((width, HEIGHT), Image.LANCZOS)

def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)

pixels = [rgb565(*image.getpixel((x, y))) for y in range(HEIGHT) for x in range(width)]
lines = [", ".join(f"0x{p:04X}" for p in pixels[i:i + 16]) for i in range(0, len(pixels), 16)]
out = root / "firmware/tft-display/logo_aerosense.h"
out.write_text(
    "// Generated by tools/make_logo.py from public/assets/aerosense-logo.svg. Do not edit by hand.\n"
    "#pragma once\n#include <stdint.h>\n#ifndef PROGMEM\n#define PROGMEM\n#endif\n"
    f"constexpr int16_t LOGO_W = {width};\nconstexpr int16_t LOGO_H = {HEIGHT};\n"
    "const uint16_t AEROSENSE_LOGO[] PROGMEM = {\n  " + ",\n  ".join(lines) + "\n};\n")
print(f"{out} {width}x{HEIGHT}")
