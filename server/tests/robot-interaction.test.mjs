import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const source = await readFile(new URL("../../n8n/robot-interaction.js", import.meta.url), "utf8");
const plan = new Function(source.slice(0, source.indexOf("\nreturn { json:")) + "\nreturn planRobot;")();
test("robot wakes once per presence session and never sleeps or accepts an unrelated answer while busy", () => {
  const now = Date.now();
  const base = { robot_id: "aerobot-01", event_id: "event-1", state: "sleep", event: "presence", observed_at: new Date(now).toISOString() };
  const run = patch => plan({ ...base, ...patch }, now);
  const waking = run({});
  assert.equal(waking.next_state, "awake");
  assert.equal(waking.steps[0].expression, "waking");
  assert.deepEqual(waking.steps[0].keyframes.map(k => k.eyes), ["closed", "half_open", "open", "blink", "open"]);
  assert.equal(waking.dispatch, false);
  assert.equal(run({}).command_id, waking.command_id);
  assert.equal(run({ state: "awake" }).execute, false);
  assert.equal(run({ quiet: true }).execute, false);
  assert.equal(run({ last_greeted_at: new Date(now - 5000).toISOString() }).reason, "greeting_cooldown");
  assert.equal(run({ observed_at: new Date(now - 31000).toISOString() }).execute, false);
  assert.equal(run({ event: "wakeword" }).next_state, "listening");
  assert.equal(run({ event: "question", state: "listening" }).next_state, "thinking");
  const answer = { event: "answer", state: "thinking", job_id: "job-1", active_job_id: "job-1", text: "Hindari asap.", audio_ready: true, answer_expression: "concerned" };
  assert.equal(run(answer).steps[1].expression, "concerned");
  assert.equal(run({ ...answer, answer_expression: "inject-command" }).steps[1].expression, "neutral");
  assert.equal(run({ ...answer, job_id: "job-2" }).execute, false);
  assert.equal(run({ ...answer, audio_ready: false }).reason, "audio_not_ready");
  assert.equal(run({ event: "audio_finished", state: "speaking", job_id: "job-2", active_job_id: "job-1" }).execute, false);
  assert.equal(run({ event: "idle_timeout", state: "speaking", last_interaction_at: new Date(now - 180000).toISOString() }).execute, false);
  assert.equal(run({ event: "idle_timeout", state: "awake", last_interaction_at: new Date(now - 180000).toISOString() }).next_state, "sleep");
});
